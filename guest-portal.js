function currentCopy() { return copy[language]; }
function escapeHtml(value) { return String(value).replace(/[&<>"']/g, character => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#039;' })[character]); }
function parseDate(value) { return new Date(`${value}T12:00:00`); }
function nightCount(reservation) { return Math.round((parseDate(reservation.checkOut) - parseDate(reservation.checkIn)) / 86400000); }
function guestCount(reservation) { return reservation.adults + reservation.children; }
function plural(total, one, many) { return `${total} ${total === 1 ? one : many}`; }
function formatDate(value, short = false) { return new Intl.DateTimeFormat(language === 'es' ? 'es-MX' : 'en-US', short ? { month: 'short', day: 'numeric' } : { weekday: 'long', month: 'long', day: 'numeric', year: 'numeric' }).format(parseDate(value)); }
function formatMoney(value) { return new Intl.NumberFormat(language === 'es' ? 'es-MX' : 'en-US', { style: 'currency', currency: 'MXN', currencyDisplay: 'code', maximumFractionDigits: 0 }).format(Number(value || 0)); }
function maskEmail(value) { return value.replace(/(.{2}).+(@.+)/, '$1••••$2'); }
function statusText(reservation) { return reservation.status === 'checkedIn' ? currentCopy().statusCheckedIn : currentCopy().statusConfirmed; }
function sourceText(source) { return source === 'bookingCom' ? currentCopy().bookingCom : currentCopy().direct; }
function requestTypeText(type) { const map = { dates: 'changeDates', guests: 'changeGuests', arrival: 'arrivalQuestion', amenity: 'amenityQuestion', special: 'specialRequest', other: 'other' }; return currentCopy()[map[type] || 'other']; }

function showToast(message) {
  clearTimeout(toastTimer);
  toast.textContent = message;
  toast.classList.add('show');
  toastTimer = setTimeout(() => toast.classList.remove('show'), 2800);
}

function showView(view, focus = true) {
  let activeSection = null;
  document.querySelectorAll('.portal-view').forEach(section => {
    const active = section.dataset.view === view;
    section.hidden = !active;
    section.classList.toggle('active', active);
    if (active) activeSection = section;
  });
  document.querySelectorAll('[data-portal-view]').forEach(button => {
    const active = button.dataset.portalView === view;
    button.classList.toggle('active', active);
    if (active) button.setAttribute('aria-current', 'page');
    else button.removeAttribute('aria-current');
  });
  const mobile = document.getElementById('mobileViewSelect');
  if (mobile) mobile.value = view;
  window.scrollTo({ top: 0, behavior: 'smooth' });
  if (focus) setTimeout(() => activeSection?.focus({ preventScroll: true }), 250);
}

function previewRequestStorageKey() { return `ichkiichpan-preview-requests-${previewKey}`; }
function loadPreviewRequests() {
  if (!activePreview || !previewKey) return;
  try {
    const saved = JSON.parse(sessionStorage.getItem(previewRequestStorageKey()) || '[]');
    if (Array.isArray(saved)) activePreview.requests = [...saved, ...activePreview.requests];
  } catch (_) { /* Ignore invalid preview-only session data. */ }
}
function savePreviewRequests() {
  if (!activePreview || !previewKey) return;
  const savedOnly = activePreview.requests.filter(request => request.previewCreated);
  sessionStorage.setItem(previewRequestStorageKey(), JSON.stringify(savedOnly));
}

function renderRequests() {
  const wrap = document.getElementById('requestHistory');
  if (!activePreview.requests.length) {
    wrap.innerHTML = `<div class="empty-request"><strong>${currentCopy().noRequests}</strong><p>${currentCopy().noRequestsBody}</p></div>`;
    return;
  }
  wrap.innerHTML = activePreview.requests.map(request => {
    const date = request.sentNow ? currentCopy().sentNow : formatDate(request.date, true);
    const text = typeof request.text === 'string' ? request.text : request.text[language] || request.text.en;
    return `<div class="request-item"><div><span>${escapeHtml(date)}</span><strong>${escapeHtml(requestTypeText(request.type))}</strong><p>${escapeHtml(text)}</p></div><em>${escapeHtml(currentCopy()[request.status] || currentCopy().requestReceived)}</em></div>`;
  }).join('');
}

