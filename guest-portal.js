document.getElementById('copyCodeButton')?.addEventListener('click', async () => {
  if (!activePreview) return;
  try {
    await navigator.clipboard.writeText(activePreview.code);
    showToast(currentCopy().codeCopied);
  } catch (_) {
    showToast(currentCopy().copyFailed);
  }
});

document.getElementById('saveArrivalButton')?.addEventListener('click', () => {
  if (!activePreview) return;
  sessionStorage.setItem(`ichkiichpan-preview-arrival-${previewKey}`, document.getElementById('arrivalTime').value);
  document.getElementById('arrivalFeedback').textContent = currentCopy().arrivalSaved;
  showToast(currentCopy().arrivalSaved);
});

requestForm?.addEventListener('submit', event => {
  event.preventDefault();
  const invalid = [...requestForm.elements].find(field => typeof field.checkValidity === 'function' && !field.checkValidity());
  if (invalid) { invalid.focus(); return; }
  if (!activePreview) return;
  const data = new FormData(requestForm);
  activePreview.requests.unshift({ type: data.get('type'), text: data.get('message'), status: 'requestReceived', sentNow: true, previewCreated: true });
  savePreviewRequests();
  renderRequests();
  document.getElementById('requestMessage').textContent = currentCopy().requestSaved;
  requestForm.reset();
  showToast(currentCopy().requestSaved);
});

